#!/usr/bin/env node
// Refreshes the snapshots bundled with the extension, which it uses until its own first download:
//   shortener-snapshot.txt  from the community shortener lists the extension syncs daily;
//   company-endings.json    the single-company ("brand") endings in ICANN's list of internet endings,
//                           which the extension downloads once a month ([5.90-2] in shared.js).
// Nothing in either is written by hand. Run from the extension folder on an internet-connected computer
// (Node 18 or newer), before a release:
//     node tools/refresh-snapshot.js
// The extension checks every entry again when it loads a file (major sites are removed from the
// shortener list, malformed lines and endings ignored), exactly as it does for its own downloads.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const LISTS = [
    'https://raw.githubusercontent.com/PeterDaveHello/url-shorteners/master/list',
    'https://raw.githubusercontent.com/boutetnico/url-shorteners/master/list.txt'
];
const DOMAIN_RE = /^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$/;
const OUT = path.join(ROOT, 'shortener-snapshot.txt');
const ENDINGS_OUT = path.join(ROOT, 'company-endings.json');

async function shorteners() {
    const domains = new Set();
    for (const url of LISTS) {
        const res = await fetch(url);
        if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
        let count = 0;
        for (const line of (await res.text()).split('\n')) {
            const d = line.trim().toLowerCase();
            if (d && !d.startsWith('#') && DOMAIN_RE.test(d)) { domains.add(d); count++; }
        }
        console.log(`${url}: ${count} domains`);
    }
    if (domains.size < 100) throw new Error(`Only ${domains.size} domains found; snapshot left unchanged.`);
    const header = [
        '# Bundled shortener snapshot: used on a fresh install until the community lists have been',
        '# downloaded once, and as a fallback while a list cannot be reached.',
        `# Generated ${new Date().toISOString().slice(0, 10)} by tools/refresh-snapshot.js from:`,
        ...LISTS.map(u => `#   ${u}`),
        ''
    ];
    fs.writeFileSync(OUT, header.join('\n') + [...domains].sort().join('\n') + '\n');
    console.log(`Wrote ${domains.size} domains to shortener-snapshot.txt`);
}

// The same reading of ICANN's list as the extension's (companyEndingsFromIcann in shared.js).
async function companyEndings() {
    const ctx = { console, URL, chrome: undefined };
    vm.createContext(ctx);
    vm.runInContext(fs.readFileSync(path.join(ROOT, 'shared.js'), 'utf8'), ctx, { filename: 'shared.js' });
    const url = vm.runInContext('COMPANY_ENDINGS_URL', ctx);
    const min = vm.runInContext('COMPANY_ENDINGS_MIN', ctx);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    const json = await res.json();
    const data = vm.runInContext('companyEndingsFromIcann', ctx)(json);
    if (data.count < min) throw new Error(`Only ${data.count} single-company endings found; snapshot left unchanged.`);
    const out = { source: url, listUpdated: String(json.updatedOn || ''), generated: new Date().toISOString().slice(0, 10),
                  note: 'Generated by tools/refresh-snapshot.js; not edited by hand.', operators: data.operators, endings: data.endings };
    fs.writeFileSync(ENDINGS_OUT, JSON.stringify(out, null, 1) + '\n');
    console.log(`Wrote ${data.count} single-company endings (${data.operators.length} registries) to company-endings.json`);
}

(async () => {
    let failed = 0;
    for (const [name, job] of [['shortener-snapshot.txt', shorteners], ['company-endings.json', companyEndings]]) {
        try { await job(); } catch (e) { failed++; console.error(`${name} not refreshed:`, e.message); }
    }
    process.exit(failed ? 1 : 0);
})();
